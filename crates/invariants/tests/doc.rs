//! `INVARIANTS.md`, the readable list of every check, is generated from the checks themselves.

use std::{env, fs, path::Path};

use invariants_core::markdown;
use tempo_invariants::all;

#[test]
fn invariants_md_lists_every_check() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("INVARIANTS.md");
    let want = format!(
        "# Tempo invariants\n\n\
         Every check in `tempo_invariants::all()`, generated by `crates/invariants/tests/doc.rs`. \
         Do not edit: regenerate with \
         `UPDATE_INVARIANTS=1 cargo test -p tempo-invariants --test doc`.\n\n{}",
        markdown(all())
    );
    if env::var("UPDATE_INVARIANTS").as_deref() == Ok("1") {
        fs::write(&path, want).expect("INVARIANTS.md is writable");
        return;
    }
    let have = fs::read_to_string(&path).unwrap_or_default();
    assert!(
        have == want,
        "{} is stale: run UPDATE_INVARIANTS=1 cargo test -p tempo-invariants --test doc",
        path.display()
    );
}
