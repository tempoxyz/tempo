/// Magic bytes for the state bloat binary format (8 bytes)
const MAGIC: &[u8; 8] = b"TEMPOSB\x00";

/// Expected format version
const VERSION: u16 = 1;

/// Read-ahead over the dump file, and again over what a compressed one unpacks to.
const READ_BUFFER: usize = 64 * 1024 * 1024;

/// ETL collector file size (200 MiB per temp file before spilling a new one).
const ETL_FILE_SIZE: usize = 200 * 1024 * 1024;

/// Storage entries handed to the hash worker at a time; each chunk is hashed in parallel.
const WORKER_CHUNK_SIZE: usize = 4096;

/// Chunks in flight between the reader and the hash worker.
const HASH_WORKER_QUEUE_DEPTH: usize = 64;

/// Subtries an account's storage trie is built from in parallel: one per leading nibble.
const STORAGE_SUBTRIES: u8 = 16;

/// Accounts with at least this many loaded slots get their storage trie built by nibble;
/// smaller ones are left to the sequential state root pass.
const PARALLEL_TRIE_MIN_SLOTS: u64 = 1_000_000;

/// Nodes a subtrie build holds before handing them to the writer; few in tests, to span batches.
const SUBTRIE_BATCH_NODES: usize = if cfg!(test) { 4 } else { 100_000 };

/// Initialize state from a binary dump file.
#[derive(Debug, Parser)]
pub struct InitFromBinaryDump<C: reth_cli::chainspec::ChainSpecParser = TempoChainSpecParser> {
    #[command(flatten)]
    env: EnvironmentArgs<C>,

    /// Path to the binary state dump file.
    ///
    /// The file should be generated by `tempo-xtask generate-state-bloat`.
    #[arg(value_name = "BINARY_DUMP_FILE")]
    state: PathBuf,

    /// Leave the loaded slots out of the storage change sets and the history index.
    ///
    /// They are the bulk of what this command writes and record only that every slot was
    /// empty before block 0. A prune checkpoint at block 0 stands in for them, so block 0's
    /// change set reads as pruned.
    #[arg(long)]
    skip_genesis_history: bool,
}

impl<C: reth_cli::chainspec::ChainSpecParser<ChainSpec: EthChainSpec + EthereumHardforks>>
    InitFromBinaryDump<C>
{
    /// Execute the init-from-binary-dump command.
    pub(crate) async fn execute<N>(self, runtime: Runtime) -> eyre::Result<()>
    where
        N: CliNodeTypes<ChainSpec = C::ChainSpec>,
    {
        info!(target: "tempo::cli", "Tempo init-from-binary-dump starting");

        let etl_dir = self
            .env
            .datadir
            .clone()
            .resolve_datadir(self.env.chain.chain())
            .data_dir()
            .join("etl");
        let environment = self.env.init::<N>(AccessRights::RW, runtime)?;
        let provider_factory = environment.provider_factory;

        let provider_rw = provider_factory.database_provider_rw()?;

        // Verify we're at genesis (block 0)
        let last_block = provider_rw.last_block_number()?;
        ensure!(
            last_block == 0,
            "init-from-binary-dump must be run on a freshly initialized database at block 0, \
             but found block {last_block}"
        );

        info!(target: "tempo::cli", path = %self.state.display(), "Loading binary state dump");

        let mut reader = open_dump(&self.state)?;

        let mut total_entries = 0u64;
        let mut total_blocks = 0u64;

        // Track addresses and their account data for hashing
        let mut accounts_seen: AddressMap<LoadedAccount> = AddressMap::default();

        // ETL collectors: accumulate entries sorted, spill to disk when full
        let mut hash_chunk: Vec<(B256, B256, CompactU256)> = Vec::with_capacity(WORKER_CHUNK_SIZE);
        // Skipping also leaves the segment genesis wrote where it is, rather than rewriting it.
        let mut genesis_history = if self.skip_genesis_history {
            None
        } else {
            Some(GenesisHistory::new(
                &etl_dir,
                provider_rw.storage_changeset(0)?,
            )?)
        };

        // The hash worker owns the hashed ETL collector: it keccaks each chunk across the rayon
        // pool, inserts on its own thread, and returns the collector when the sender drops.
        let (hash_tx, hash_rx) =
            mpsc::sync_channel::<Vec<(B256, B256, CompactU256)>>(HASH_WORKER_QUEUE_DEPTH);
        let hashed_etl_dir = etl_dir;
        let hash_worker =
            thread::spawn(move || -> eyre::Result<Collector<Vec<u8>, CompactU256>> {
                let mut hashed_collector: Collector<Vec<u8>, CompactU256> =
                    Collector::new(ETL_FILE_SIZE, Some(hashed_etl_dir));
                while let Ok(chunk) = hash_rx.recv() {
                    let hashed: Vec<(Vec<u8>, CompactU256)> = chunk
                        .into_par_iter()
                        .map(|(hashed_address, slot, value)| {
                            let mut hashed_key = Vec::with_capacity(64);
                            hashed_key.extend_from_slice(hashed_address.as_slice());
                            hashed_key.extend_from_slice(keccak256_uncached(slot).as_slice());
                            (hashed_key, value)
                        })
                        .collect();
                    for (hashed_key, value) in hashed {
                        hashed_collector
                            .insert(hashed_key, value)
                            .wrap_err("hashed ETL insert failed")?;
                    }
                }
                Ok(hashed_collector)
            });

        // Process blocks from binary file
        loop {
            let Some(header_buf) = next_header(&mut reader)? else {
                break;
            };

            // Validate magic
            ensure!(
                &header_buf[..8] == MAGIC,
                "invalid magic bytes in block header"
            );

            // Validate version
            let version = u16::from_be_bytes([header_buf[8], header_buf[9]]);
            ensure!(
                version == VERSION,
                "unsupported binary format version {version}, expected {VERSION}"
            );

            // Skip flags (2 bytes at offset 10)

            // Read address (20 bytes at offset 12)
            let mut address_bytes = [0u8; 20];
            address_bytes.copy_from_slice(&header_buf[12..32]);
            let address = alloy_primitives::Address::from(address_bytes);

            // Read pair count (8 bytes at offset 32)
            let pair_count = u64::from_be_bytes(header_buf[32..40].try_into().unwrap());

            info!(
                target: "tempo::cli",
                %address,
                pair_count,
                "Processing token storage block"
            );

            // Ensure the account exists in the canonical state table (only on first encounter).
            // The binary dump is chunked: generate-state-bloat writes one block per token
            // per chunk, so the same token address appears in multiple blocks. This entry
            // is Vacant on the first chunk and Occupied on subsequent ones.
            // Preserving the genesis account is critical: TIP20 tokens have bytecode (0xEF)
            // set during genesis, and overwriting with Account::default() would clear the
            // code hash, making the token appear uninitialized.
            let loaded = match accounts_seen.entry(address) {
                Entry::Occupied(e) => e.into_mut(),
                Entry::Vacant(e) => {
                    let hashed_address = keccak256_uncached(address);
                    let account = provider_rw
                        .tx_ref()
                        .get::<tables::HashedAccounts>(hashed_address)?
                        .ok_or_else(|| {
                            eyre::eyre!(
                                "state bloat references account {address} that is missing from genesis"
                            )
                        })?;
                    e.insert(LoadedAccount {
                        account,
                        hashed_address,
                        slots: 0,
                    })
                }
            };
            let hashed_address = loaded.hashed_address;

            // Read entries into the hashed ETL collector.
            let mut entry_buf = [0u8; 64];
            let start = Instant::now();
            let mut last_log = start;

            for i in 0..pair_count {
                reader
                    .read_exact(&mut entry_buf)
                    .wrap_err("failed to read storage entry")?;

                let slot = B256::from_slice(&entry_buf[..32]);
                let value = U256::from_be_bytes::<32>(entry_buf[32..64].try_into().unwrap());

                // Skip zero values (they represent deletion)
                if value.is_zero() {
                    continue;
                }

                let compact_value = CompactU256::from(value);

                if let Some(history) = genesis_history.as_mut() {
                    history.record(address, slot)?;
                }

                // Queue raw data for parallel hashing
                hash_chunk.push((hashed_address, slot, compact_value));

                // Send full batches to the hashing worker thread.
                if hash_chunk.len() >= WORKER_CHUNK_SIZE {
                    let chunk =
                        std::mem::replace(&mut hash_chunk, Vec::with_capacity(WORKER_CHUNK_SIZE));
                    hash_tx.send(chunk).wrap_err("hash worker disconnected")?;
                }

                total_entries += 1;
                loaded.slots += 1;

                log_collection_progress(&address, i, pair_count, start, &mut last_log);
            }

            total_blocks += 1;
        }

        // Send any remaining entries to the worker and join.
        if !hash_chunk.is_empty() {
            hash_tx
                .send(std::mem::take(&mut hash_chunk))
                .wrap_err("hash worker disconnected")?;
        }
        drop(hash_tx);
        let mut hashed_collector = hash_worker
            .join()
            .map_err(|_| eyre::eyre!("hash worker panicked"))??;

        info!(
            target: "tempo::cli",
            total_blocks,
            total_entries,
            "Entries collected, merging genesis hashed storage into ETL collector..."
        );

        // Merge existing genesis hashed storage into the collector.
        {
            let tx = provider_rw.tx_ref();
            let mut cursor = tx.cursor_read::<tables::HashedStorages>()?;
            let mut genesis_count = 0usize;
            let walker = cursor.walk(None)?;
            for row in walker {
                let (hashed_address, entry) = row?;
                let mut key = Vec::with_capacity(64);
                key.extend_from_slice(hashed_address.as_slice());
                key.extend_from_slice(entry.key.as_slice());
                hashed_collector
                    .insert(key, CompactU256::from(entry.value))
                    .wrap_err("ETL insert of genesis hashed storage failed")?;
                genesis_count += 1;
            }
            info!(
                target: "tempo::cli",
                genesis_count,
                "Genesis hashed storage entries merged into collector"
            );
        }

        let storage_settings = provider_rw.cached_storage_settings();
        ensure!(
            storage_settings.storage_v2,
            "init-from-binary-dump only supports storage v2 databases"
        );

        let history_workers = genesis_history.map(|history| history.spawn(&provider_factory));

        // Both workers finish before any error leaves, so a failed load exits with nothing
        // still writing.
        let hashed = write_hashed_state(&provider_rw, hashed_collector, &accounts_seen);
        let history = history_workers.map(|workers| workers.map(JoinHandle::join));
        hashed?;

        // Either the entries are written or the marker stands in for them; nothing writes both
        // and nothing writes neither.
        match history {
            Some(results) => {
                for result in results {
                    result.map_err(|_| eyre::eyre!("genesis history worker panicked"))??;
                }
            }
            None => provider_rw
                .save_prune_checkpoint(PruneSegment::StorageHistory, genesis_history_pruned())?,
        }

        // Rebuild the merkle trie from scratch so the sparse trie cache on
        // block 1 doesn't hit stale genesis nodes and stall on a full rebuild.
        // Cleared before the commit, so a failed load leaves no stale node behind.
        provider_rw.tx_ref().clear::<tables::AccountsTrie>()?;
        provider_rw.tx_ref().clear::<tables::StoragesTrie>()?;

        // Committed here so the storage tries below can be read from many threads. A load that
        // fails past this point needs a fresh datadir, as any failed load does.
        provider_rw.commit()?;

        info!(
            target: "tempo::cli",
            addresses = accounts_seen.len(),
            "Hashed accounts written, computing state root and trie nodes..."
        );

        let trie_start = Instant::now();
        let provider_rw = provider_factory.database_provider_rw()?;

        // The state root pass reads these nodes instead of walking the slots under them.
        let large_accounts: Vec<B256> = accounts_seen
            .values()
            .filter(|loaded| loaded.slots >= PARALLEL_TRIE_MIN_SLOTS)
            .map(|loaded| loaded.hashed_address)
            .collect();
        let mut trie_writes =
            parallel_storage_tries(&provider_factory, &provider_rw, &large_accounts)?;
        info!(
            target: "tempo::cli",
            accounts = large_accounts.len(),
            nodes = trie_writes,
            elapsed = ?trie_start.elapsed(),
            "Storage tries built by nibble"
        );

        let mut resume: Option<IntermediateStateRootState> = None;

        // Incrementally compute the merkle root over all hashed accounts/storages.
        let state_root = {
            use reth_trie_db::{
                DatabaseHashedCursorFactory, DatabaseTrieCursorFactory, PackedKeyAdapter,
            };
            type DbStateRoot<'a, TX> = reth_trie::StateRoot<
                DatabaseTrieCursorFactory<&'a TX, PackedKeyAdapter>,
                DatabaseHashedCursorFactory<&'a TX>,
            >;

            // Compute state root in chunks, flushing trie nodes to disk between iterations.
            loop {
                match DbStateRoot::<_>::from_tx(provider_rw.tx_ref())
                    .with_intermediate_state(resume)
                    .root_with_progress()?
                {
                    StateRootProgress::Progress(state, _, updates) => {
                        trie_writes += provider_rw.write_trie_updates(updates)?;
                        info!(
                            target: "tempo::cli",
                            last_key = %state.account_root_state.last_hashed_key,
                            trie_writes,
                            elapsed = ?trie_start.elapsed(),
                            "Flushing trie updates"
                        );
                        resume = Some(*state);
                    }
                    StateRootProgress::Complete(root, _, updates) => {
                        trie_writes += provider_rw.write_trie_updates(updates)?;
                        break root;
                    }
                }
            }
        };

        info!(
            target: "tempo::cli",
            %state_root,
            trie_writes,
            elapsed = ?trie_start.elapsed(),
            "State root computed"
        );

        // Final commit
        provider_rw.commit()?;

        info!(
            target: "tempo::cli",
            total_blocks,
            total_entries,
            %state_root,
            "Binary state dump loaded successfully"
        );

        Ok(())
    }
}

/// Loads the sorted hashed storage into its table, then the hashed accounts. Consumes the
/// collector, so its spill files are gone before the trie is built.
fn write_hashed_state<P>(
    provider: &P,
    mut hashed_collector: Collector<Vec<u8>, CompactU256>,
    accounts: &AddressMap<LoadedAccount>,
) -> eyre::Result<()>
where
    P: DBProvider<Tx: DbTxMut> + HashingWriter,
{
    // The table is cleared first so append_dup ordering is guaranteed.
    let total_hashes = hashed_collector.len();
    provider.tx_ref().clear::<tables::HashedStorages>()?;
    let mut hashed_cursor = provider
        .tx_ref()
        .cursor_dup_write::<tables::HashedStorages>()?;
    load_etl_to_cursor(
        &mut hashed_collector,
        total_hashes,
        "hashed storage",
        |k, v| {
            hashed_cursor.append_dup(
                B256::from_slice(&k[..32]),
                StorageEntry {
                    key: B256::from_slice(&k[32..]),
                    value: v,
                },
            )
        },
    )?;
    drop(hashed_cursor);

    info!(target: "tempo::cli", total_hashes, "Storage written, writing hashed accounts...");

    // The real account metadata keeps genesis code hashes (TIP20 tokens have 0xEF code).
    provider.insert_account_for_hashing(
        accounts
            .iter()
            .map(|(addr, loaded)| (*addr, Some(loaded.account))),
    )?;
    Ok(())
}

/// An account the dump loads slots into.
struct LoadedAccount {
    /// As genesis left it, code hash included.
    account: Account,
    hashed_address: B256,
    /// Non-zero slots loaded into it.
    slots: u64,
}

/// Builds the storage tries of `accounts` across the rayon pool, one subtrie per leading nibble
/// of the hashed slot, and writes the nodes reth's own walk would store. Returns their count.
fn parallel_storage_tries<N: ProviderNodeTypes>(
    factory: &ProviderFactory<N>,
    writer: &impl TrieWriter,
    accounts: &[B256],
) -> eyre::Result<usize> {
    let subtries: Vec<Subtrie> = accounts
        .iter()
        .flat_map(|&account| (0..STORAGE_SUBTRIES).map(move |nibble| (account, nibble)))
        .collect();
    let (tx, rx) = mpsc::sync_channel(2);
    thread::scope(|scope| {
        // Once the writer stops, a failed send ends each build and skips those not started.
        let builders = scope.spawn(move || {
            let _ = subtries
                .into_par_iter()
                .try_for_each_with(tx, |tx, subtrie| {
                    build_subtrie(factory, subtrie, tx).or_else(|err| tx.send((subtrie, Err(err))))
                });
        });
        let written = write_subtries(writer, rx);
        builders
            .join()
            .map_err(|_| eyre::eyre!("storage trie builder panicked"))?;
        written
    })
}

/// Writes each batch of subtrie nodes under its nibble. Returns the nodes written.
fn write_subtries(
    writer: &impl TrieWriter,
    rx: mpsc::Receiver<SubtrieNodes>,
) -> eyre::Result<usize> {
    let mut written = 0;
    for ((hashed_address, nibble), nodes) in rx {
        let prefix = Nibbles::from_nibbles([nibble]);
        let mut updates = StorageTrieUpdates::default();
        for (path, mut node) in nodes? {
            // Only a subtrie's own root carries a hash; in the account's trie it is inner.
            node.root_hash = None;
            updates.storage_nodes.insert(prefix.join(&path), node);
        }
        written += writer.write_trie_updates(TrieUpdates {
            storage_tries: B256Map::from_iter([(hashed_address, updates)]),
            ..Default::default()
        })?;
    }
    Ok(written)
}

/// An account's hashed address and the leading nibble of the hashed slots under one subtrie.
type Subtrie = (B256, u8);

/// A batch of one subtrie's stored nodes, paths relative to its nibble, or why the build failed.
type SubtrieNodes = (Subtrie, eyre::Result<HashMap<Nibbles, BranchNodeCompact>>);

/// Builds the subtrie under one leading nibble of an account's hashed slots, over the keys with
/// that nibble stripped, and sends its stored nodes in batches.
fn build_subtrie<N: ProviderNodeTypes>(
    factory: &ProviderFactory<N>,
    (hashed_address, nibble): Subtrie,
    tx: &mpsc::SyncSender<SubtrieNodes>,
) -> eyre::Result<()> {
    let send = |nodes| {
        tx.send(((hashed_address, nibble), Ok(nodes)))
            .map_err(|_| eyre::eyre!("storage trie writer stopped"))
    };
    // A large account's subtrie can outlast the read transaction timeout.
    let provider = factory.provider()?.disable_long_read_transaction_safety();
    let mut cursor = provider
        .tx_ref()
        .cursor_dup_read::<tables::HashedStorages>()?;
    let mut builder = HashBuilder::default().with_updates(true);
    let mut first = B256::ZERO;
    first[0] = nibble << 4;
    let mut entry = cursor.seek_by_key_subkey(hashed_address, first)?;
    while let Some(StorageEntry { key, value }) = entry {
        if key[0] >> 4 != nibble {
            break;
        }
        builder.add_leaf(
            Nibbles::unpack(key).slice(1..),
            alloy_rlp::encode_fixed_size(&value).as_ref(),
        );
        if builder.updates_len() >= SUBTRIE_BATCH_NODES {
            let (rest, nodes) = builder.split();
            builder = rest.with_updates(true);
            send(nodes)?;
        }
        entry = cursor.next_dup_val()?;
    }
    builder.root();
    send(builder.split().1)
}

/// The dump, unpacked on the way through if it was compressed. Its first four bytes say which.
fn open_dump(path: &Path) -> eyre::Result<Box<dyn BufRead>> {
    let file = File::open(path).wrap_err_with(|| format!("failed to open {}", path.display()))?;
    let mut reader = BufReader::with_capacity(READ_BUFFER, file);
    let head = reader
        .fill_buf()
        .wrap_err_with(|| format!("failed to read {}", path.display()))?;
    // `pzstd` puts a skippable frame ahead of each frame.
    let compressed = head
        .first_chunk()
        .map(|magic| u32::from_le_bytes(*magic))
        .is_some_and(|magic| {
            magic == MAGICNUMBER || magic & MAGIC_SKIPPABLE_MASK == MAGIC_SKIPPABLE_START
        });
    if compressed {
        let mut decoder =
            zstd::Decoder::with_buffer(reader).wrap_err("failed to open zstd dump")?;
        // zstd's largest window, for dumps made with `zstd --long`.
        decoder.window_log_max(31)?;
        return Ok(Box::new(BufReader::with_capacity(READ_BUFFER, decoder)));
    }
    Ok(Box::new(reader))
}

/// The next block header, or `None` once the dump is spent. Bytes that stop partway through
/// one are a truncated file, not an end.
fn next_header(reader: &mut impl BufRead) -> eyre::Result<Option<[u8; 40]>> {
    if reader
        .fill_buf()
        .wrap_err("failed to read block header")?
        .is_empty()
    {
        return Ok(None);
    }
    let mut header = [0u8; 40];
    match reader.read_exact(&mut header) {
        Ok(()) => Ok(Some(header)),
        Err(err) if err.kind() == std::io::ErrorKind::UnexpectedEof => {
            Err(err).wrap_err("dump ends partway through a block header")
        }
        Err(err) => Err(err).wrap_err("failed to read block header"),
    }
}

/// Storage change sets and history for the loaded slots: what each held before block 0, which
/// is nothing. `--skip-genesis-history` leaves all of it out and marks the history pruned.
struct GenesisHistory {
    changesets: Collector<Vec<u8>, CompactU256>,
    history: Collector<Vec<u8>, CompactU256>,
    /// Slots genesis already recorded, which the dump must not record again.
    already_recorded: HashSet<Vec<u8>>,
}

impl GenesisHistory {
    fn new(etl_dir: &Path, genesis: Vec<(BlockNumberAddress, StorageEntry)>) -> eyre::Result<Self> {
        let mut this = Self {
            changesets: Collector::new(ETL_FILE_SIZE, Some(etl_dir.to_path_buf())),
            history: Collector::new(ETL_FILE_SIZE, Some(etl_dir.to_path_buf())),
            already_recorded: HashSet::new(),
        };
        for (index, entry) in genesis {
            let raw_key = raw_storage_key(index.address(), entry.key);
            this.already_recorded.insert(raw_key.clone());
            this.changesets
                .insert(raw_key, CompactU256::from(entry.value))
                .wrap_err("storage changeset ETL insert of genesis storage failed")?;
        }
        Ok(this)
    }

    fn record(&mut self, address: alloy_primitives::Address, slot: B256) -> eyre::Result<()> {
        let raw_key = raw_storage_key(address, slot);
        if self.already_recorded.contains(&raw_key) {
            return Ok(());
        }
        self.changesets
            .insert(raw_key.clone(), CompactU256::from(U256::ZERO))
            .wrap_err("storage changeset ETL insert failed")?;
        self.history
            .insert(raw_key, CompactU256::from(U256::ZERO))
            .wrap_err("storage history ETL insert failed")?;
        Ok(())
    }

    /// Write both, in parallel with the caller.
    fn spawn<N>(self, factory: &ProviderFactory<N>) -> [JoinHandle<eyre::Result<()>>; 2]
    where
        N: ProviderNodeTypes,
    {
        let changeset_factory = factory.clone();
        let rocksdb = factory.rocksdb_provider();
        [
            thread::spawn(move || write_storage_changesets(changeset_factory, self.changesets)),
            thread::spawn(move || write_storage_history(&rocksdb, self.history)),
        ]
    }
}

/// What `--skip-genesis-history` leaves instead: a slot with no history reads from the plain
/// state. State reads at every block still resolve; only block 0's change set reads as pruned.
fn genesis_history_pruned() -> PruneCheckpoint {
    PruneCheckpoint {
        block_number: Some(0),
        tx_number: None,
        prune_mode: PruneMode::Before(1),
    }
}

fn write_storage_changesets<P>(
    provider: P,
    mut collector: Collector<Vec<u8>, CompactU256>,
) -> eyre::Result<()>
where
    P: StaticFileProviderFactory + Send + 'static,
{
    info!(target: "tempo::cli", "Writing storage changesets...");

    provider
        .static_file_provider()
        .delete_segment(StaticFileSegment::StorageChangeSets)?;

    let mut writer = provider.get_static_file_writer(0, StaticFileSegment::StorageChangeSets)?;
    writer.begin_storage_changeset(0)?;
    let total = collector.len();
    load_storage_etl(
        &mut collector,
        total,
        "storage changeset",
        |address, key, value| {
            writer.append_storage_changeset_entry(StorageBeforeTx {
                address,
                key,
                value,
            })?;
            Ok(())
        },
    )?;
    drop(writer);

    Ok(())
}

/// Marks every slot in `collector` as last changed at block 0.
///
/// No lookup first: nothing else can be there at block 0, and a miss re-reads an
/// index block too big to cache.
fn write_storage_history(
    rocksdb: &RocksDBProvider,
    mut collector: Collector<Vec<u8>, CompactU256>,
) -> eyre::Result<()> {
    info!(target: "tempo::cli", "Writing storage history...");

    let mut batch = rocksdb.batch_with_auto_commit();
    let block_zero_history =
        tables::BlockNumberList::new([0]).expect("single block is always sorted");
    let total = collector.len();
    load_storage_etl(
        &mut collector,
        total,
        "storage history",
        |address, key, _| {
            batch.put::<tables::StoragesHistory>(
                StorageShardedKey::last(address, key),
                &block_zero_history,
            )?;
            Ok(())
        },
    )?;
    batch.commit()?;

    Ok(())
}

/// Composite ETL key for unhashed storage, sorted by address then slot.
fn raw_storage_key(address: alloy_primitives::Address, slot: B256) -> Vec<u8> {
    let mut key = Vec::with_capacity(52);
    key.extend_from_slice(address.as_slice());
    key.extend_from_slice(slot.as_slice());
    key
}

fn decode_raw_storage_key(key: &[u8]) -> (alloy_primitives::Address, B256) {
    (
        alloy_primitives::Address::from_slice(&key[..20]),
        B256::from_slice(&key[20..]),
    )
}

/// Iterate a raw storage ETL collector, deduplicate consecutive entries with the
/// same `(address, slot)` key, and call `write` for each unique entry.
fn load_storage_etl(
    collector: &mut Collector<Vec<u8>, CompactU256>,
    total: usize,
    label: &str,
    mut write: impl FnMut(alloy_primitives::Address, B256, U256) -> eyre::Result<()>,
) -> eyre::Result<()> {
    let total = total.max(1);
    let interval = (total / 10).max(1);
    let mut pending: Option<(Vec<u8>, Vec<u8>)> = None;
    for (index, item) in collector.iter()?.enumerate() {
        if index > 0 && index % interval == 0 {
            info!(
                target: "tempo::cli",
                progress = format_args!("{:.2}%", (index as f64 / total as f64) * 100.0),
                "Inserting {label}"
            );
        }

        let (key, value) = item.wrap_err("ETL iteration failed")?;
        if let Some((ref prev_key, ref prev_val)) = pending
            && *prev_key != key
        {
            let (address, storage_key) = decode_raw_storage_key(prev_key);
            write(
                address,
                storage_key,
                CompactU256::decompress_owned(prev_val.clone())?.into(),
            )?;
        }
        pending = Some((key, value));
    }

    if let Some((key, val)) = pending {
        let (address, storage_key) = decode_raw_storage_key(&key);
        write(
            address,
            storage_key,
            CompactU256::decompress_owned(val)?.into(),
        )?;
    }

    Ok(())
}

/// Iterate a sorted ETL collector, deduplicate consecutive entries with the same key
/// (keeping the last value), and call `append` for each unique entry.
fn load_etl_to_cursor(
    collector: &mut Collector<Vec<u8>, CompactU256>,
    total: usize,
    label: &str,
    mut append: impl FnMut(&[u8], U256) -> Result<(), reth_db_api::DatabaseError>,
) -> eyre::Result<()> {
    let interval = (total / 10).max(1);
    let mut pending: Option<(Vec<u8>, Vec<u8>)> = None;
    for (index, item) in collector.iter()?.enumerate() {
        if index > 0 && index % interval == 0 {
            info!(
                target: "tempo::cli",
                progress = format_args!("{:.2}%", (index as f64 / total as f64) * 100.0),
                "Inserting {label}"
            );
        }

        let (key, value) = item.wrap_err("ETL iteration failed")?;
        if let Some((ref prev_key, ref prev_val)) = pending
            && *prev_key != key
        {
            append(
                prev_key,
                CompactU256::decompress_owned(prev_val.clone())?.into(),
            )
            .wrap_err("cursor append failed")?;
        }
        pending = Some((key, value));
    }
    if let Some((key, val)) = pending {
        append(&key, CompactU256::decompress_owned(val)?.into())
            .wrap_err("cursor append failed")?;
    }
    Ok(())
}

/// Log collection progress every 5 seconds and on the final entry. The clock is read once
/// per 65,536 entries: read per entry, it was most of the reader's own time.
fn log_collection_progress(
    address: &alloy_primitives::Address,
    index: u64,
    total: u64,
    start: Instant,
    last_log: &mut Instant,
) {
    let done = index + 1;
    if done != total && !done.is_multiple_of(65_536) {
        return;
    }
    if last_log.elapsed() >= Duration::from_secs(5) || done == total {
        let pct = ((index + 1) as f64 / total as f64) * 100.0;
        let elapsed = start.elapsed();
        let pairs_per_sec = (index + 1) as f64 / elapsed.as_secs_f64();
        info!(
            target: "tempo::cli",
            %address,
            progress = format_args!("{}/{} ({pct:.0}%)", index + 1, total),
            elapsed = ?elapsed,
            pairs_per_sec = pairs_per_sec as u64,
            "Collecting storage"
        );
        *last_log = Instant::now();
    }
}

