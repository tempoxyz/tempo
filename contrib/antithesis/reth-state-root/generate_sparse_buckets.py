#!/usr/bin/env python3
"""Generate finite, named local-neighbourhood coverage functions; no runtime code generation."""
import argparse
import json
from pathlib import Path

# Local IDs shift down by 544 from the combined-bank baseline. Compare semantic
# (depth bucket, target nibble, pattern), never numeric IDs, across experiments.
LOCAL_COUNT = 7 * 16 * 256


def arms():
    result = []
    for depth in range(7):
        for target in range(16):
            for pattern in range(256):
                result.append((f'local_{depth}_{target}_{pattern}', (depth, target, pattern)))
    result.extend([('proof_no_parent', ()), ('invalid_proof', ())])
    return result


def generate():
    all_arms = arms()
    lines = ['// @generated by generate_sparse_buckets.py; do not edit.',
             '// Local IDs are baseline IDs minus 544; compare semantic keys across runs.',
             f'const ARM_COUNT: usize = {len(all_arms)};',
             'const LOCAL_START: usize = 0;',
             f'const NO_PARENT: usize = {LOCAL_COUNT};',
             'const INVALID_PROOF: usize = NO_PARENT + 1;']
    for index, (name, _) in enumerate(all_arms):
        lines.append(f'coverage_arm!(coverage_{name}, {index});')
    lines.append('static ARMS: [fn(&Observation); ARM_COUNT] = [')
    lines.extend(f'    coverage_{name},' for name, _ in all_arms)
    lines.extend(['];', '#[cfg(test)]', 'static ARM_NAMES: [&str; ARM_COUNT] = ['])
    lines.extend(f'    "{name}",' for name, _ in all_arms)
    lines.append('];')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--check', action='store_true')
    mode.add_argument('--metadata', action='store_true', help='Print the stable ID/name manifest as JSON without writing files')
    args = parser.parse_args()
    if args.metadata:
        print(json.dumps({'arm_count': len(arms()), 'family_count': 1, 'encoder_count': 0, 'local_count': LOCAL_COUNT, 'sandwich_count': 0, 'control_count': 2,
                          'arms': [{'id': index, 'name': name} for index, (name, _) in enumerate(arms())]}))
        raise SystemExit(0)
    path = Path(__file__).with_name('src') / 'sparse_buckets_generated.rs'
    content = generate()
    if args.check:
        if path.read_text() != content:
            raise SystemExit('Sparse coverage generation is stale; run generate_sparse_buckets.py')
    else:
        path.write_text(content)
    print(f'{len(arms())} distinct sparse coverage functions (including invalid input)')
