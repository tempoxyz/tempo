#!/usr/bin/env python3
"""Generate finite, named coverage functions and dispatch; no runtime code generation."""
import argparse
import json
from pathlib import Path

MASKS = ('state', 'revealed', 'leaf', 'occupied_unrevealed', 'revealed_nonleaf')


def families():
    result = [('depth', ['depth'], [(x,) for x in range(7)]),
              ('root', ['root'], [(x,) for x in range(2)])]
    for i, name in enumerate(MASKS):
        result.extend([(name + '_count', [f'counts[{i}]'], [(x,) for x in range(5)]),
                       (name + '_shape', [f'shapes[{i}]'], [(x,) for x in range(5)]),
                       (name + '_count_shape', [f'counts[{i}]', f'shapes[{i}]'],
                        [(0, 0), (1, 1), (2, 2), (2, 3), (3, 2), (3, 3), (4, 2), (4, 3), (4, 4)])])
    count_shapes = [(0, 0), (1, 1), (2, 2), (2, 3), (3, 2), (3, 3), (4, 2), (4, 3), (4, 4)]
    for i, name in enumerate(MASKS):
        result.append(('depth_' + name + '_count_shape', ['depth', f'counts[{i}]', f'shapes[{i}]'],
                       [(depth, count, shape) for depth in range(7) for count, shape in count_shapes]))
    for name, lhs, rhs in [('state_revealed_count', 0, 1), ('revealed_leaf_count', 1, 2)]:
        result.append((name, [f'counts[{lhs}]', f'counts[{rhs}]'], [(a, b) for a in range(5) for b in range(a + 1)]))
    result.append(('relationship_counts', ['counts[3]', 'counts[4]'], [(a, b) for a in range(5) for b in range(5) if (a, b) != (4, 4)]))
    result.append(('root_count_triple', ['root', 'counts[0]', 'counts[1]', 'counts[2]'],
                   [(r, a, b, c) for r in range(2) for a in range(5) for b in range(a + 1) for c in range(b + 1)]))
    return result


def arms():
    result = []
    for family, _, keys in families():
        for key in keys:
            result.append((family + '_' + '_'.join(map(str, key)), key))
    result.append(('invalid_observation', ()))
    return result


def generate():
    lines = ['// @generated by generate_sparse_buckets.py; do not edit.', f'const ARM_COUNT: usize = {len(arms())};']
    index = 0
    for family, _, keys in families():
        for key in keys:
            name = family + '_' + '_'.join(map(str, key))
            lines.append(f'coverage_arm!(coverage_{name}, {index});')
            index += 1
    lines.append(f'coverage_arm!(coverage_invalid_observation, {index});')
    lines.extend(['fn dispatch(observation: &Observation) {', '    let depth = depth_bucket(observation.branch_path_len);',
                  '    let root = u8::from(observation.is_root);', '    let masks = observation.masks();',
                  '    let counts = masks.map(count_bucket);', '    let shapes = masks.map(shape_bucket);'])
    for family, expressions, keys in families():
        # Tuples are used even for independent dimensions, keeping generation uniform.
        lines.append('    match (' + ', '.join(expressions) + ',) {')
        for key in keys:
            name = family + '_' + '_'.join(map(str, key))
            lines.append('        (' + ', '.join(map(str, key)) + f',) => coverage_{name}(observation),')
        lines.append('        _ => coverage_invalid_observation(observation),')
        lines.append('    }')
    lines.extend(['}', '#[cfg(test)]', 'const ARMS: [fn(&Observation); ARM_COUNT] = ['])
    lines.extend(f'    coverage_{name},' for name, _ in arms())
    lines.extend(['];', '#[cfg(test)]', 'const ARM_NAMES: [&str; ARM_COUNT] = ['])
    lines.extend(f'    "{name}",' for name, _ in arms())
    lines.append('];')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--check', action='store_true')
    mode.add_argument('--metadata', action='store_true', help='Print the stable ID/name manifest as JSON without writing files')
    args = parser.parse_args()
    if args.metadata:
        print(json.dumps({'arm_count': len(arms()), 'family_count': len(families()),
                          'arms': [{'id': index, 'name': name} for index, (name, _) in enumerate(arms())]}))
        raise SystemExit(0)
    path = Path(__file__).with_name('src') / 'sparse_buckets_generated.rs'
    content = generate()
    if args.check:
        if path.read_text() != content:
            raise SystemExit('Sparse coverage generation is stale; run generate_sparse_buckets.py')
    else:
        path.write_text(content)
    print(f'{len(arms())} distinct sparse coverage functions (including invalid input)')
